// 完全模拟 IPC，独立浏览器会话，不接触用户数据库或真实汇率服务。
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
const origin = process.argv[2] || 'http://127.0.0.1:1420';
const run = (...args) => execFileSync('npx', ['--no-install', 'agent-browser', '--session', 'exchange-check', ...args], { encoding: 'utf8', timeout: 60000 });
const ev = code => JSON.parse(JSON.parse(run('eval', `JSON.stringify(${code})`).trim()));
const wait = () => run('wait', '200');
const open = query => { run('open', `${origin}/tests/exchange-rates.html${query || ''}`); wait(); };
const click = text => { ev(`(()=>{const button=[...document.querySelectorAll('button')].find(x=>x.textContent.trim()===${JSON.stringify(text)});if(!button)throw Error('missing button '+${JSON.stringify(text)});button.click();return true})()`); wait(); };
const amount = value => { run('fill', '#exchange-amount', value); wait(); };
const output = code => ev(`document.querySelector('[data-currency="${code}"] output')?.textContent`);
const search = query => { run('fill', 'input[aria-label="搜索币种名称或代码"]', query); wait(); };
const options = () => ev(`Array.from(document.querySelectorAll('[role=option]'), option => option.textContent.trim())`);
const choose = code => { ev(`(()=>{const option=[...document.querySelectorAll('[role=option]')].find(x=>x.textContent.trim().endsWith(${JSON.stringify(`(${code})`)}));if(!option)throw Error('missing currency '+${JSON.stringify(code)});option.click();return true})()`); wait(); };
const select = (selector, code) => { run('click', selector); wait(); choose(code); };
const reset = query => { open(); ev(`(()=>{localStorage.clear();return true})()`); open(query); };
let count=0;
const check = (name, fn) => { fn(); count++; console.log(`✓ ${name}`); };
try {
  reset();
  run('click', '#exchange-base'); wait();
  search('加坡');
  check('来源币种按中文名称片段搜索', () => assert.deepEqual(options(), ['新加坡元 (SGD)']));
  search('sG');
  check('来源币种按代码片段搜索且忽略大小写', () => assert.deepEqual(options(), ['新加坡元 (SGD)']));
  search('不存在的币种');
  check('搜索无结果有明确提示', () => { assert.deepEqual(options(), []); assert.match(ev(`document.querySelector('.glass-select-empty').textContent`), /没有匹配的选项/); });
  run('press', 'Escape'); wait(); run('click', '#exchange-base'); wait();
  check('关闭重开清空搜索并恢复选项', () => { assert.equal(ev(`document.querySelector('input[aria-label="搜索币种名称或代码"]').value`), ''); assert.ok(options().length > 1); });
  search('sG'); choose('SGD');
  check('来源搜索后选择并重新换算', () => { assert.match(ev(`document.querySelector('#exchange-base').textContent`), /SGD/); assert.equal(output('USD'), '76.92'); assert.equal(ev(`document.querySelector('input[aria-label="搜索币种名称或代码"]')===null`), true); });
  reset();
  run('click', '[aria-label="目标币种 1"]'); wait(); search('大利');
  check('目标币种按中文名称片段搜索', () => assert.deepEqual(options(), ['澳大利亚元 (AUD)']));
  search('aU');
  check('目标币种按代码片段搜索且忽略大小写', () => assert.deepEqual(options(), ['澳大利亚元 (AUD)']));
  search('cN');
  check('搜索不能选到来源币种', () => assert.deepEqual(options(), []));
  search('eU');
  check('搜索不能选到已有其他目标币种', () => assert.deepEqual(options(), []));
  search('aU'); run('press', 'Enter'); wait();
  check('目标搜索后键盘选择更新换算', () => { assert.equal(output('AUD'), '21.43'); assert.equal(ev(`document.querySelector('[data-currency="USD"]')===null`), true); });
  reset();
  check('100 人民币多币种金额与单位汇率', () => {
    assert.equal(output('USD'), '14.29'); assert.equal(output('EUR'), '12.86'); assert.equal(output('HKD'), '111.43'); assert.equal(output('JPY'), '2,143');
    assert.match(ev(`document.querySelector('[data-currency="USD"] small').textContent`), /1 CNY = 0.1428571429 USD/);
  });
  const calls=ev('window.__calls.length');
  amount('200');
  check('金额变化只做本机计算',()=>{assert.equal(output('USD'),'28.57');assert.equal(ev('window.__calls.length'),calls);});
  click('添加币种');
  check('新增币种与重复禁选',()=>{assert.equal(ev('document.querySelectorAll(".exchange-row").length'),5);});
  run('click','[aria-label="目标币种 1"]'); wait();
  check('目标选项排除来源及已有其他币种',()=>{assert.equal(options().some(label=>label.endsWith('(CNY)')),false);assert.equal(options().some(label=>label.endsWith('(EUR)')),false);});
  choose('AUD');
  check('更换目标币种',()=>assert.equal(output('AUD'),'42.86'));
  run('click','[aria-label="移除 AUD"]');wait();
  check('删除目标币种',()=>assert.equal(ev('document.querySelectorAll(".exchange-row").length'),4));
  amount('0');check('零金额',()=>assert.equal(output('EUR'),'0.00'));
  amount('-1');check('非法金额',()=>{assert.equal(output('EUR'),'—');assert.equal(ev('document.querySelector("#exchange-amount").getAttribute("aria-invalid")'),'true');});
  amount('0.00000001');check('极小金额保留非零含义',()=>assert.equal(output('EUR'),'< 0.01'));
  amount('100'); select('[aria-label="目标币种 4"]','USD'); select('#exchange-base','USD');
  check('切换来源币种并替换同币种目标',()=>{assert.equal(output('CNY'),'700.00');assert.equal(output('EUR'),'90.00');});
  ev(`window.__mode='pending'`);click('刷新汇率');
  select('#exchange-base','GBP');
  check('来源切换期间不显示旧来源结果',()=>assert.equal(output('EUR'),'—'));
  ev(`(()=>{window.__pending.find(p=>p.base==='USD').resolve(window.__snapshot('USD'));return true})()`);wait();
  check('迟到成功不能污染新来源',()=>assert.equal(output('EUR'),'—'));
  ev(`(()=>{window.__pending.find(p=>p.base==='GBP').resolve(window.__snapshot('GBP'));return true})()`);wait();
  check('当前来源响应正确换算',()=>assert.equal(output('EUR'),'112.50'));
  ev(`window.__mode='pending'`);click('刷新汇率');select('#exchange-base','CAD');
  ev(`(()=>{window.__pending.findLast(p=>p.base==='GBP').reject('迟到失败');window.__pending.find(p=>p.base==='CAD').resolve(window.__snapshot('CAD'));return true})()`);wait();
  check('迟到失败不污染新来源',()=>{assert.equal(output('EUR'),'64.29');assert.equal(ev('document.querySelector("[role=alert]")===null'),true);});
  ev(`window.__mode='fail'`);click('刷新汇率');
  check('刷新失败保留旧金额并显示失败',()=>{assert.equal(output('EUR'),'64.29');assert.match(ev('document.querySelector("[role=alert]").textContent'),/仍使用上次/);});
  ev(`window.__mode='success'`);click('刷新汇率');
  check('失败后可重试',()=>assert.equal(ev('document.querySelector("[role=alert]")===null'),true));
  amount('321');open();
  check('重新加载恢复金额、来源和目标偏好',()=>{assert.equal(ev('document.querySelector("#exchange-amount").value'),'321');assert.match(ev('document.querySelector("#exchange-base").textContent'),/CAD/);assert.equal(ev('document.querySelectorAll(".exchange-row").length'),4);});
  ev(`(()=>{document.querySelectorAll('.exchange-remove').forEach(b=>b.click());return true})()`);wait();
  check('空列表仍可添加币种',()=>{assert.equal(ev('document.querySelectorAll(".exchange-row").length'),0);assert.match(ev('document.querySelector(".exchange-empty").textContent'),/添加币种/);});
  click('添加币种');check('空列表恢复换算',()=>assert.equal(ev('document.querySelectorAll(".exchange-row").length'),1));
  reset('?mode=fail');check('首次失败不伪造金额',()=>{assert.equal(output('USD'),'—');assert.match(ev('document.querySelector("[role=alert]").textContent'),/模拟汇率查询失败/);});
  ev(`window.__mode='success'`);click('刷新汇率');check('首次失败可重试成功',()=>assert.equal(output('USD'),'14.29'));
  reset('?preview=1');check('浏览器预览无假汇率',()=>{assert.equal(output('USD'),'—');assert.equal(ev('window.__calls.length'),0);assert.match(ev('document.body.textContent'),/请在栖点桌面应用中/);});
  reset();
  for(const theme of ['light','dark']){run('set','viewport','900','800');ev(`document.documentElement.dataset.theme='${theme}'`);check(`${theme} 900px桌面无横向溢出`,()=>assert.equal(ev('document.documentElement.scrollWidth>window.innerWidth'),false));}
  console.log(`汇率转换 ${count} 项模拟浏览器验收通过`);
} finally {run('close');}

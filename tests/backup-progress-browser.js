// agent-browser eval --stdin；仅模拟 IPC，不发起真实云端上传。
(async () => {
  const results=[];
  const assert=(ok,text)=>{if(!ok)throw Error(text);results.push(text);};
  const wait=async fn=>{for(let i=0;i<100;i++){if(fn())return;await new Promise(r=>setTimeout(r,25));}throw Error('等待备份界面超时');};
  const button=text=>[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===text);
  await wait(()=>button('立即备份'));
  window.__deferCreate=true;
  button('立即备份').click();
  await wait(()=>window.__finishCreate && document.querySelector('[data-backup-id]'));
  const id=document.querySelector('[data-backup-id]').dataset.backupId;
  assert(document.querySelectorAll('[data-backup-id]').length===1,'请求未结束即出现一条记录');
  assert(button('正在备份…').disabled && button('正在备份…').querySelector('.backup-spinner'),'创建按钮立即显示转圈和忙碌状态');
  assert(window.__calls.find(c=>c.name==='backup_create').args.id===id,'占位记录与原生请求使用同一ID');
  window.__advance('database',20,100);
  await wait(()=>document.querySelector('[data-phase="database"] progress')?.value===20);
  assert(document.querySelector('[data-phase="database"]').textContent.includes('20 / 100 页'),'数据库进度按实际页数显示');
  window.__advance('packing',262144,1048576);
  await wait(()=>document.querySelector('[data-phase="packing"] progress')?.value===25);
  assert(document.querySelector('[data-phase="packing"]').textContent.includes('25%'),'执行中持续接收打包进度');
  window.__advance('uploading',524288,1048576);
  await wait(()=>document.querySelector('[data-phase="uploading"] progress')?.value===50);
  assert(document.querySelectorAll('[data-backup-id]').length===1,'阶段更新不重复生成记录');
  window.__emit('backup-progress',{workspaceId:'other',dataRoot:'/mock/perch',record:{...window.__state.records[0],progress:{phase:'uploading',completed:99,total:100}}});
  await new Promise(r=>setTimeout(r,40));
  assert(document.querySelector('[data-phase="uploading"] progress').value===50,'其他工作空间的进度不会污染当前记录');
  window.__advance('verifying',1048576,1048576);
  await wait(()=>document.querySelector('[data-phase="verifying"]'));
  assert(!document.querySelector('[data-phase="verifying"] progress').hasAttribute('value'),'上传字节发完仍等待云端确认，不伪造100%成功');
  assert(!button('还原'),'确认响应前不提供还原');
  window.__finishCreate('unknown');
  await wait(()=>button('核验结果') && !button('核验结果').disabled);
  assert(document.body.textContent.includes('文件可能已经在云端'),'待确认有明确解释和核验入口');
  assert(!window.__calls.some(c=>c.name==='backup_retry'),'未知结果不会自动重传');
  window.__verifyOutcome='error';button('核验结果').click();
  await wait(()=>document.body.textContent.includes('核验遇到 HTTP 403'));
  assert(!!button('核验结果') && !button('重新上传'),'核验失败保持待确认');
  await wait(()=>!button('核验结果').disabled);
  window.__verifyOutcome='missing';button('核验结果').click();
  await wait(()=>button('重新上传') && !button('重新上传').disabled);
  assert(!window.__calls.some(c=>c.name==='backup_retry'),'远端未找到时仍需用户点击重新上传');
  button('重新上传').click();
  await wait(()=>button('还原') && !button('还原').disabled);
  assert(window.__calls.filter(c=>c.name==='backup_retry').length===1 && window.__calls.find(c=>c.name==='backup_retry').args.id===id,'手动重传沿用原记录');
  window.__state.records[0].status='unknown';window.__state.records[0].retryAvailable=false;window.__state.records[0].error='旧记录上传未确认';window.__emit();
  await wait(()=>button('核验结果'));
  button('核验结果').click();
  await wait(()=>button('重新备份') && !button('重新备份').disabled);
  assert(!button('重新上传'),'缺少旧备份本地文件时提示重新备份');
  return {passed:results.length,results};
})()

// node tests/bug-confirm-browser.js http://127.0.0.1:1421
// 仅操作模拟 IPC fixture，禁止连接真实禅道。
import { execFileSync } from "node:child_process";
import assert from "node:assert/strict";
const origin = process.argv[2] || "http://127.0.0.1:1421";
const run = (...args) => execFileSync("npx", ["--yes", "agent-browser", "--session", "bug-confirm-test", ...args], { encoding: "utf8", timeout: 60000 });
const ev = code => JSON.parse(JSON.parse(run("eval", `JSON.stringify(${code})`).trim()));
const wait = () => run("wait", "200");
const button = text => ev(`(() => { const b=[...document.querySelectorAll('dialog button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}); if(!b) throw Error('找不到按钮 '+${JSON.stringify(text)}); return {disabled:b.disabled}; })()`);
const click = text => ev(`(() => { [...document.querySelectorAll('dialog button')].find(b=>b.textContent.trim()===${JSON.stringify(text)}).click(); return true; })()`);
const writes = () => ev(`window.__bugCalls.filter(c=>c.name==='zentao_bug_transition').length`);
const open = query => { run("open", `${origin}/tests/bugs.html${query || ''}`); wait(); };
const detail = () => { run("click", ".bugs-title"); wait(); };
open(); detail(); click("确认"); wait();
assert.equal(writes(),0,"进入确认表单不能同次点击误提交");
assert.equal(ev(`document.querySelectorAll('dialog [role=combobox]').length`),0,"确认不要求选择人员");
run("fill", '[aria-label="操作备注"]', "已按复现步骤核验");
ev(`window.__bugFail=true`); click("确认 BUG"); wait();
assert.equal(ev(`document.querySelector('[aria-label="操作备注"]').value`),"已按复现步骤核验","失败保留备注");
assert.deepEqual(ev(`window.__bugCalls.findLast(c=>c.name==='zentao_bug_transition').args`),{id:"bug-0",revision:1,action:"confirm",payload:{comment:"已按复现步骤核验"}});
ev(`window.__bugFail=false`); click("确认 BUG"); wait();
assert.equal(ev(`window.__fixtureBugs.find(b=>b.id==='bug-0').status`),"active","确认独立于状态");
assert.equal(ev(`window.__fixtureBugs.find(b=>b.id==='bug-0').confirmed`),true);
detail(); assert.equal(button("确认").disabled,true,"已确认不能重确认");
open("?confirmed=unknown");
assert.match(ev(`document.querySelector('.bugs-table').textContent`),/待同步/);
detail(); assert.equal(button("确认").disabled,true,"未知确认状态不可提交");
open(); detail(); click("确认"); wait();
ev(`window.__bugWriteDeferred=true`);
ev(`(() => { const b=[...document.querySelectorAll('dialog button')].find(b=>b.textContent.trim()==='确认 BUG'); b.click(); b.click(); return true; })()`); wait();
assert.equal(writes(),1,"快速双击只能提交一次");
assert.equal(button("正在提交…").disabled,true);
ev(`window.__resolveBugWrite({...window.__fixtureBugs[0],confirmed:true,revision:2})`); wait();
open(); detail(); click("指派"); wait();
assert.equal(writes(),0,"进入指派表单不能误提交");
run("click", '[aria-label="指派给"][role="combobox"]');
run("fill", '[aria-label="搜索姓名或账号"]', "唐家乐"); run("press","Enter");
run("fill", '[aria-label="操作备注"]', "交由唐家乐处理");
ev(`window.__bugFail=true`); click("提交指派"); wait();
assert.equal(ev(`document.querySelector('[aria-label="操作备注"]').value`),"交由唐家乐处理");
assert.deepEqual(ev(`window.__bugCalls.findLast(c=>c.name==='zentao_bug_transition').args.payload`),{comment:"交由唐家乐处理",assignedTo:"tangjiale"});
ev(`window.__bugFail=false`); click("提交指派"); wait();
assert.equal(ev(`window.__fixtureBugs.some(b=>b.id==='bug-0')`),false,"转派他人后移出我的 BUG");
assert.equal(ev(`document.querySelector('.bugs-table')?.textContent.includes('登录页面测试 BUG') || false`),false);
open();
ev(`document.querySelectorAll('.bugs-status-filters button')[0].click()`); wait();
const colors = () => ev(`(() => { const cells=[...document.querySelectorAll('.bugs-table td')]; return ['已确认','未确认','待同步'].map(label=>{const cell=cells.find(c=>c.textContent.trim()===label); if(!cell) throw Error('缺失确认列 '+label); const tag=cell.firstElementChild || cell; const s=getComputedStyle(tag); return {label,color:s.color,background:s.backgroundColor};}); })()`);
const light=colors(); assert.equal(new Set(light.map(c=>c.color)).size,3,"浅色三态颜色不同");
ev(`document.documentElement.dataset.theme='dark'`); wait();
const dark=colors(); assert.equal(new Set(dark.map(c=>c.color)).size,3,"深色三态颜色不同");
assert.notDeepEqual(light,dark,"暗色主题应应用主题颜色");
console.log(JSON.stringify({confirmEntry:true,confirmPayload:true,failureDraft:true,independentStatus:true,confirmedDisabled:true,unknownDisabled:true,doubleSubmit:true,assignEntry:true,assignPayload:true,assignmentRemoval:true,lightColors:true,darkColors:true}));
run("close");

// node tests/bug-assignees-browser.js http://127.0.0.1:1421
// 仅访问模拟 IPC 的 BUG fixture，禁止操作真实禅道。
import { execFileSync } from "node:child_process";
import assert from "node:assert/strict";
const origin = process.argv[2] || "http://127.0.0.1:1421";
const run = (...args) => execFileSync("npx", ["--yes", "agent-browser", "--session", "assignees-test", ...args], { encoding: "utf8", timeout: 60000 });
const ev = code => JSON.parse(JSON.parse(run("eval", `JSON.stringify(${code})`).trim()));
const wait = () => run("wait", "200");
const clickText = text => ev(`(() => { [...document.querySelectorAll('dialog button')].find(b => b.textContent.trim() === ${JSON.stringify(text)}).click(); return true; })()`);
const selector = '[aria-label="BUG 指派给"][role="combobox"]';
const search = '[aria-label="搜索姓名或账号"]';
const writes = () => ev(`window.__bugCalls.filter(c => ['zentao_bug_save','zentao_bug_transition'].includes(c.name)).length`);
const openEdit = mode => {
  run("open", `${origin}/tests/bugs.html`); wait();
  if (mode) ev(`window.__bugAssigneeMode = ${JSON.stringify(mode)}`);
  run("click", ".bugs-title"); wait(); clickText("编辑 BUG"); wait();
};
openEdit();
assert.match(ev(`document.querySelector('${selector}').textContent`), /测试用户（tester）/);
run("click", selector); run("fill", search, "唐家乐");
assert.equal(ev(`document.querySelectorAll('[role=option]').length`), 1);
run("click", '[role="option"]');
assert.match(ev(`document.querySelector('${selector}').textContent`), /唐家乐（tangjiale）/);
run("click", selector); run("fill", search, "same.");
assert.equal(ev(`document.querySelectorAll('[role=option]').length`), 2, "重名账号必须能区分");
run("fill", search, "wuminzheng"); run("press", "Enter");
assert.equal(writes(), 0, "搜索 Enter 只选择，不提交表单");
assert.match(ev(`document.querySelector('${selector}').textContent`), /吴敏政/);
run("click", selector); run("fill", search, "不存在的人员");
assert.match(ev(`document.querySelector('.glass-select-empty').textContent`), /没有匹配/);
run("press", "Escape");
assert.equal(ev(`document.querySelectorAll('dialog[open]').length`), 1, "Esc 只关闭下拉");
run("click", selector); run("fill", search, "tester");
ev(`(() => { const input=document.querySelector('${search}'); input.dispatchEvent(new KeyboardEvent('keydown',{key:'Enter',isComposing:true,bubbles:true,cancelable:true})); return true; })()`);
assert.equal(writes(), 0, "中文输入确认不提交");
assert.equal(ev(`!!document.querySelector('${search}')`), true, "组合输入不能选择人员");
run("press", "ArrowDown"); run("press", "ArrowUp"); run("press", "Enter");
ev(`window.__bugFail = true`); clickText("保存到禅道"); wait();
assert.equal(ev(`window.__bugCalls.findLast(c => c.name === 'zentao_bug_save').args.value.assignedTo`), "tester");
assert.equal(ev(`document.querySelector('${selector}').disabled`), false, "失败解除禁用");
openEdit("fail");
assert.match(ev(`document.querySelector('${selector}').textContent`), /测试用户/);
assert.equal(ev(`document.querySelector('${selector}').disabled`), true);
assert.match(ev(`document.querySelector('[role=alert]').textContent`), /人员列表加载失败/);
ev(`window.__bugAssigneeMode = ''`); clickText("重新加载人员"); wait();
assert.equal(ev(`document.querySelector('${selector}').disabled`), false);
openEdit("empty"); run("click", selector);
assert.equal(ev(`document.querySelector('[role=option]').getAttribute('aria-disabled')`), "true", "空目录保留当前人员但不能改选");
run("fill", search, "其他人员"); assert.match(ev(`document.querySelector('.glass-select-empty').textContent`), /没有匹配/);
openEdit("pending");
run("fill", 'dialog input', "延迟加载期间修改标题");
ev(`window.__resolveAssignees(window.__bugAssignees)`); wait();
assert.equal(ev(`document.querySelector('dialog input').value`), "延迟加载期间修改标题");
assert.match(ev(`document.querySelector('${selector}').textContent`), /测试用户/);
openEdit("pending");
ev(`window.__oldAssigneeResolve = window.__resolveAssignees`);
run("click", 'dialog [title="关闭"]'); wait();
ev(`window.__bugAssigneeMode = ''`);
run("click", ".bugs-title"); wait(); clickText("编辑 BUG"); wait();
ev(`window.__oldAssigneeResolve([{account:'stale',realname:'过期人员'}])`); wait();
run("click", selector);
assert.equal(ev(`document.querySelector('[role=listbox]').textContent.includes('过期人员')`), false, "关闭后的请求不可覆盖重开列表");
run("press", "Escape"); clickText("取消编辑"); wait(); clickText("解决"); wait();
run("click", '[aria-label="处理后指派给"][role="combobox"]'); run("fill", search, "唐家乐"); run("press", "Enter");
ev(`window.__bugFail = true`); clickText("确认解决 BUG"); wait();
assert.equal(ev(`window.__bugCalls.findLast(c => c.name === 'zentao_bug_transition').args.payload.assignedTo`), "tangjiale", "操作指派提交账号");
ev(`(window.__bugFail = false, window.__bugWriteDeferred = true)`);
clickText("确认解决 BUG"); wait();
assert.equal(ev(`document.querySelector('[aria-label="处理后指派给"][role="combobox"]').disabled`), true, "保存期间不能重新选择指派人");
ev(`window.__resolveBugWrite({id:'bug-0', revision:2})`); wait();
run("open", `${origin}/tests/bugs.html`); wait();
ev(`document.querySelectorAll('.bugs-status-filters button')[0].click()`); wait();
ev(`document.querySelector('.bugs-title').click()`); wait(); clickText("激活"); wait();
assert.match(ev(`document.querySelector('[aria-label="处理后指派给"][role="combobox"]').textContent`), /测试用户/);
run("click", '[aria-label="处理后指派给"][role="combobox"]'); run("fill", search, "same.b"); run("press", "Enter");
ev(`window.__bugFail = true`); clickText("确认激活 BUG"); wait();
assert.equal(ev(`window.__bugCalls.findLast(c => c.name === 'zentao_bug_transition').args.payload.assignedTo`), "same.b", "激活表单同样保存所选账号");
console.log(JSON.stringify({ nameSearch:true, accountSearch:true, duplicateNames:true, keyboard:true, composition:true, noResults:true, escape:true, accountPayload:true, retry:true, emptyList:true, delayedLoad:true, staleRequest:true, transitionSelect:true, busy:true, activateSelect:true }));
